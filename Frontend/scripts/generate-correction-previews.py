"""Generate the single-photo color/edge previews using the team's actual AI pipeline.

Run from the repository root: python Frontend/scripts/generate-correction-previews.py
Requires the AI development dependencies (numpy, opencv-python, Pillow).
All images share the existing CC0 Farmhouse in Provence crop; see calibration/calibration.json.
Only color/edge are baked in. App Skia applies contrast/brightness/sharpness afterward.
"""
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))
from Backend.ai.correction import correct_image  # noqa: E402


def main():
    output = ROOT / "Frontend/assets/images/correction-preview"
    output.mkdir(parents=True, exist_ok=True)
    source = (ROOT / "Frontend/assets/images/calibration/farmhouse-original.jpg").read_bytes()
    levels = range(0, 101, 20)
    neutral = []
    groups = {}
    count = 0
    for color in ("normal", "protan", "deutan", "tritan"):
        rows = []
        for severity in ([0] if color == "normal" else levels):
            if color != "normal" and severity == 0:
                rows.append("NEUTRAL")
                continue
            images = []
            for edge in levels:
                if color == "normal" and edge == 0:
                    images.append("require('../calibration/farmhouse-original.jpg')")
                    continue
                filename = f"farmhouse-{color}-{severity}-edge-{edge}.jpg"
                profile = dict(color_type=color, severity=severity / 100, edge=edge / 100,
                               contrast=1, brightness=0, sharpness=0)
                (output / filename).write_bytes(correct_image(source, profile))
                images.append(f"require('./{filename}')")
                count += 1
            row = "[" + ", ".join(images) + "]"
            if color == "normal":
                neutral = images
            rows.append(row)
        groups[color] = rows
        print(f"Generated {color} previews", flush=True)
    content = ["// Generated by scripts/generate-correction-previews.py. Do not hand-edit.",
               "// AI color/edge correction on one CC0 Farmhouse in Provence crop.",
               "const NEUTRAL = [" + ", ".join(neutral) + "] as const;",
               "export const COMBINED_PREVIEWS = {"]
    content.append("  normal: [NEUTRAL],")
    for color in ("protan", "deutan", "tritan"):
        content.append(f"  {color}: [\n    " + ",\n    ".join(groups[color]) + "\n  ],")
    content.append("} as const;\n")
    (output / "index.ts").write_text("\n".join(content), encoding="utf-8")
    print(f"Done: {count} images plus original, {sum(p.stat().st_size for p in output.glob('*.jpg')) / 1024 / 1024:.1f} MiB", flush=True)


if __name__ == "__main__":
    main()
